-- Akoma in-app technical problem reports.
-- Safe additive migration: creates a separate table and does not modify profiles,
-- matches, messages, or existing user-report records.
create table if not exists public.app_feedback (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  category text not null default 'Something else' check (char_length(category) <= 80),
  details text not null check (char_length(details) between 10 and 2000),
  page text not null default '' check (char_length(page) <= 80),
  app_version text not null default '' check (char_length(app_version) <= 80),
  status text not null default 'open' check (status in ('open','reviewing','resolved','closed')),
  created_at timestamptz not null default now()
);

alter table public.app_feedback enable row level security;
drop policy if exists app_feedback_insert_own on public.app_feedback;
create policy app_feedback_insert_own on public.app_feedback
  for insert to authenticated with check (reporter_id = auth.uid());
drop policy if exists app_feedback_admin_read on public.app_feedback;
create policy app_feedback_admin_read on public.app_feedback
  for select to authenticated using (public.is_admin());
drop policy if exists app_feedback_admin_update on public.app_feedback;
create policy app_feedback_admin_update on public.app_feedback
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

grant insert on public.app_feedback to authenticated;
grant select, update on public.app_feedback to authenticated;
grant usage, select on sequence public.app_feedback_id_seq to authenticated;
